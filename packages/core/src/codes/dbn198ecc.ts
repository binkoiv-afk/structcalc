import type { Section } from "../geometry/sections";

/** φe за табл. Ж.3 з білінійною інтерполяцією; за межами таблиці — крайні значення (у запас для λ̄ < 0,5). */
export function phiE(lamBar: number, mef: number): number {
  const lo = (arr: number[], x: number) => {
    if (x <= arr[0]) return [0, 0, 0] as const;
    for (let i = 1; i < arr.length; i++) if (x <= arr[i]) return [i - 1, i, (x - arr[i - 1]) / (arr[i] - arr[i - 1])] as const;
    const n = arr.length - 1;
    return [n, n, 0] as const;
  };
  const [r0, r1, tr] = lo(PHI_E_LAM, lamBar);
  const [c0, c1, tc] = lo(PHI_E_MEF, mef);
  const v = (r: number, c: number) => PHI_E[r][c];
  const a = v(r0, c0) + (v(r0, c1) - v(r0, c0)) * tc;
  const b = v(r1, c0) + (v(r1, c1) - v(r1, c0)) * tc;
  return (a + (b - a) * tr) / 1000;
}

/** Коефіцієнт впливу форми перерізу η, табл. Ж.2.
 *  Двотавр з ексцентриситетом у площині стінки — тип 5 (інтерполяція за Af/Aw між 0,25; 0,5; 1,0).
 *  Для замкнених перерізів (труби) прийнято η = 1 (тип 1) — потребує звірки з рисунком табл. Ж.2. */
export function etaDBN(s: Section, m: number, lamBar: number): { eta: number; type: number; approx: boolean } {
  if (s.kind !== "I") return { eta: 1, type: 1, approx: true };
  const { tf, tw } = s.dims;
  const ratio = (s.b * tf) / ((s.h - 2 * tf) * tw);
  const at = (r: 0.25 | 0.5 | 1): number => {
    if (lamBar > 5) return r === 0.25 ? 1.2 : r === 0.5 ? 1.25 : 1.3;
    if (m > 5) return r === 0.25 ? 1.2 : r === 0.5 ? 1.25 : 1.4 - 0.02 * lamBar;
    if (r === 0.25) return 1.45 - 0.05 * m - 0.01 * (5 - m) * lamBar;
    if (r === 0.5) return 1.75 - 0.1 * m - 0.02 * (5 - m) * lamBar;
    return 1.9 - 0.1 * m - 0.02 * (6 - m) * lamBar;
  };
  let eta: number;
  if (ratio <= 0.25) eta = at(0.25);
  else if (ratio <= 0.5) eta = at(0.25) + ((at(0.5) - at(0.25)) * (ratio - 0.25)) / 0.25;
  else if (ratio < 1) eta = at(0.5) + ((at(1) - at(0.5)) * (ratio - 0.5)) / 0.5;
  else eta = at(1);
  return { eta, type: 5, approx: ratio < 0.25 };
}

/** Коефіцієнт c за 10.2.5 для двотавра (тип 1 табл. 10.2), φb — як для балки з двома і більше закріпленнями. */
export function cDBN(mx: number, phiY: number, phiC: number, lamBarY: number, phiBVal: number): { c: number; alpha: number; beta: number } {
  const alpha = mx <= 1 ? 0.7 : 0.65 + 0.05 * Math.min(mx, 5);
  const beta = lamBarY <= 3.14 ? 1 : Math.sqrt(phiC / phiY);
  const c5 = (m: number) => beta / (1 + alpha * m);
  const c10 = (m: number) => 1 / (1 + (m * phiY) / phiBVal);
  let c: number;
  if (mx <= 5) c = c5(mx);
  else if (mx >= 10) c = c10(mx);
  else c = c5(5) * (2 - 0.2 * mx) + c10(10) * (0.2 * mx - 1); // (10.11)
  return { c: Math.min(c, 1), alpha, beta };
}
