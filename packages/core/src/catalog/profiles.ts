const cache = new Map<string, Section[]>();
export function familySections(id: string): Section[] {
  if (!cache.has(id)) {
    const f = FAMILIES.find((x) => x.id === id);
    if (!f) throw new Error(`Unknown family ${id}`);
    cache.set(id, f.build().sort((a, b) => a.mass - b.mass));
  }
  return cache.get(id)!;
}

export function findSection(family: string, name: string): Section | undefined {
  return familySections(family).find((s) => s.name === name);
}
